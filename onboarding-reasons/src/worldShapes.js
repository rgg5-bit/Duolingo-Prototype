// Hand-simplified continent outlines as [lon, lat] points. They're projected
// onto a 1000-unit-wide equirectangular map and smoothed into rounded,
// cartoonish blobs, so precision doesn't matter much.

const K = 1000 / 360;

export function project([lon, lat]) {
  return [(lon + 180) * K, (90 - lat) * K];
}

// Closed Catmull-Rom spline through the points -> cubic Bézier path.
function smooth(points) {
  const p = points.map(project);
  const n = p.length;
  const f = (v) => v.toFixed(1);
  let d = `M${f(p[0][0])} ${f(p[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = p[(i - 1 + n) % n];
    const p1 = p[i];
    const p2 = p[(i + 1) % n];
    const p3 = p[(i + 2) % n];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += ` C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return `${d} Z`;
}

